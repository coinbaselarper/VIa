#!/usr/bin/env python3
"""Generate common/title_sites.inc from data/sites_raw.json and data/vshift_analysis.json.
usage: gen_site_table.py SITES.json VSHIFT.json OUT.inc"""
import sys, json

KIND = dict(chkstk=1, sse4a=2, vshift_patch=3, vshift_safe=4, cpuid=5, xgetbv=6)
sites = json.load(open(sys.argv[1]))
vs = {s['rva']: s for s in json.load(open(sys.argv[2]))['sites']}
rows = []
for s in sites['sites']:
    b = bytes.fromhex(s['bytes'])
    if s['mn'] in ('insertq', 'extrq'):
        k = 'sse4a'
    elif s['mn'] == 'cpuid':
        k = 'cpuid'
    elif s['mn'] == 'xgetbv':
        k = 'xgetbv'
    elif s['mn'] == 'mov':
        k = 'chkstk'
        s = dict(s, rva=s['range'][0])
        b = None
    else:
        k = 'vshift_patch' if vs[s['rva']]['verdict'] == 'PATCH' else 'vshift_safe'
    rows.append((s['rva'], k, b, '%s %s' % (s['mn'], s['op'])))
with open(sys.argv[3], 'w') as o:
    o.write('// Generated by isa/tools/gen_site_table.py from isa/data/*.json. Do not edit.\n')
    o.write('// exe sha256 %s\n' % sites['exe_sha256'])
    o.write('static const char kTitleSha256[] = "%s";\n' % sites['exe_sha256'])
    o.write('static const TitleSite kTitleSites[] = {\n')
    for rva, k, b, text in rows:
        if b is None:
            o.write('    {0x%x, %d, 0, {}},  // __chkstk (full signature checked)\n' % (rva, KIND[k]))
            continue
        o.write('    {0x%x, %d, %d, {%s}},  // %s\n' % (rva, KIND[k], len(b), ', '.join('0x%02x' % x for x in b), text))
    o.write('};\n')
print(len(rows), 'rows')
