"""Write copies of DirectX-Headers d3d12.h / d3d12video.h whose struct-returning C++ methods use the explicit
RetVal form (the header's own non-MSVC _WIN32 branch).

MSVC passes `this` in RCX and the hidden return pointer in RDX for every struct-returning member function. clang's
Itanium C++ ABI with ms_abi puts the return pointer first (or returns small structs in RAX), so the natural-return
declarations DirectX-Headers picks without _WIN32 do not match what the guest (and the d3d12_xs proxy thunks) pass.

    python3 -I -B patch_d3d12_retval.py <src.h> <out_compiled.h> <out_for_stub_generator.h>

out_compiled.h additionally gets a non-virtual natural-return wrapper after each method so host call sites keep
`x = obj->GetDesc();`. The stub generator cannot parse those, so it reads out_for_stub_generator.h.
"""
import re
import sys

COND = "#if defined(_MSC_VER) || !defined(_WIN32)"
BLOCK = re.compile(r"#if defined\(_MSC_VER\) \|\| !defined\(_WIN32\)\n(.*?)\n#else\n(.*?)\n#endif", re.S)
NATURAL = re.compile(r"virtual\s+(.*?)\s*STDMETHODCALLTYPE\s+(\w+)\s*\((.*)\)\s*(const)?\s*=\s*0\s*;\s*$", re.S)
SAL = re.compile(r"\b_\w+_(?:\([^()]*\))?\s+")
MIDL = re.compile(r'MIDL_INTERFACE\("([0-9a-fA-F-]{36})"\)\s*(\w+)\s*:')


def param_names(params):
    params = " ".join(params.split())
    if params in ("", "void"):
        return []
    names = []
    for p in params.split(","):
        p = p.strip()
        names.append(re.findall(r"(\w+)\s*(?:\[\s*\])?$", p)[0])
    return names


def wrap(match, with_wrapper):
    natural, retval = match.group(1), match.group(2)
    if not with_wrapper:
        return "#if 0\n" + natural + "\n#else\n" + retval + "\n#endif"
    m = NATURAL.match(natural.strip())
    if not m:
        raise SystemExit("cannot parse " + natural)
    ret, name, params, const = m.groups()
    args = ", ".join(["&gta6rt_r"] + param_names(params))
    cparams = " ".join(params.split())
    if cparams == "void":
        cparams = ""
    wrapper = (f"        {ret} {name}({cparams}){' const' if const else ''} "
               f"{{ {ret} gta6rt_r; {name}({args}); return gta6rt_r; }}")
    return retval + "\n" + wrapper


def uuid_decls(text, guard):
    # Without _MSC_VER nothing declares __uuidof for these interfaces; dxguids.h covers only some of them.
    out = ["#if defined(__cplusplus) && !defined(GTA6RT_" + guard + "_UUIDS)", "#define GTA6RT_" + guard + "_UUIDS"]
    for guid, name in MIDL.findall(text):
        a, b, c, d, e = guid.split("-")
        tail = d + e
        bytes_ = ", ".join("0x" + tail[i:i + 2] for i in range(0, 16, 2))
        out.append(f"__CRT_UUID_DECL({name}, 0x{a}, 0x{b}, 0x{c}, {bytes_})")
    out.append("#endif")
    return "\n".join(out) + "\n"


def write_if_changed(path, text):
    try:
        if open(path, encoding="utf-8").read() == text:
            return
    except OSError:
        pass
    open(path, "w", encoding="utf-8").write(text)


def main():
    src, out_compiled, out_stubs = sys.argv[1:4]
    text = open(src, encoding="utf-8").read()
    n = text.count(COND)
    compiled, k1 = BLOCK.subn(lambda m: wrap(m, True), text)
    stubs, k2 = BLOCK.subn(lambda m: wrap(m, False), text)
    if not (n == k1 == k2):
        raise SystemExit(f"{src}: {n} conditions, {k1}/{k2} rewritten")
    banner = f"/* Generated by d3d12_vulkan/tools/patch_d3d12_retval.py from DirectX-Headers {src.split('/')[-1]}. */\n"
    tail = "\n" + uuid_decls(text, re.sub(r"\W", "_", src.split("/")[-1]).upper())
    if src.endswith("/d3d12.h"):
        tail += "#include <gta6rt/dx_extra_uuids.h>\n"
    write_if_changed(out_compiled, banner + "#include <windows.h>\n" + compiled + tail)
    write_if_changed(out_stubs, banner + stubs)
    print(f"{src}: {n} methods in RetVal form")


if __name__ == "__main__":
    main()
