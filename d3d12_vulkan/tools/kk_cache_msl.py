#!/usr/bin/env python3
"""The MSL sources a KosmicKrisp pipeline_cache.session.bin holds, one NNNN.metal + NNNN.entry pair each, as input for
tests/metal_cache_probe.mm. KosmicKrisp 26.3.1 serializes a shader as u32 entry-point length, u32 code length, the
entry point, then the code (kk_msl_serialize); every code blob starts with Mesa's "// Generated by Mesa compiler".

  kk_cache_msl.py SESSION_FILE OUT_DIR
"""
import os
import struct
import sys

MARKER = b"// Generated by Mesa compiler"


def main():
    data = open(sys.argv[1], "rb").read()
    out = sys.argv[2]
    os.makedirs(out, exist_ok=True)
    i = n = 0
    sizes = []
    while True:
        i = data.find(MARKER, i)
        if i < 0:
            break
        for el in range(1, 300):
            p = i - el - 8
            if p < 0:
                break
            e, c = struct.unpack_from("<II", data, p)
            if e == el and 0 < c < 50_000_000 and i + c <= len(data):
                code = data[i:i + c].rstrip(b"\0")
                with open(os.path.join(out, f"{n:04d}.metal"), "wb") as f:
                    f.write(code)
                with open(os.path.join(out, f"{n:04d}.entry"), "w") as f:
                    f.write(data[i - el:i].rstrip(b"\0").decode("latin1"))
                sizes.append(len(code))
                n += 1
                i += c
                break
        else:
            i += len(MARKER)
    if not sizes:
        print("no MSL found")
        return 1
    print(f"{n} MSL sources; bytes min/median/max {min(sizes)} {sorted(sizes)[len(sizes) // 2]} {max(sizes)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
